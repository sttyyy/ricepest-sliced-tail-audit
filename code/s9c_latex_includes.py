TABLES = ["TABLE_config", "TABLE_leakage", "TABLE_truncation", "TABLE_partition", "TABLE_partition_fcos",
          "TABLE_methods", "TABLE_ccpr", "TABLE_sensitivity", "TABLE_yst", "TABLE_methods_fcos"]


def main():
    fd = os.path.join(ROOT, "figures")
    lines = ["% Auto-generated by code/s9c_latex_includes.py (experiment-bridge).",
             "% The MVA template loads no float package, so all floats use [!htbp].", ""]
    for name, label, cap in FIGS:
        if not os.path.exists(os.path.join(fd, name + ".pdf")):
            continue
        lines += ["\\begin{figure}[!htbp]", "    \\centering",
                  f"    \\includegraphics[width=0.95\\textwidth]{{figures/{name}.pdf}}",
                  f"    \\caption{{{cap}}}", f"    \\label{{{label}}}", "\\end{figure}", ""]
    lines.append("% ---- tables (booktabs; generated by code/s9_tables.py)")
    for t in TABLES:
        if os.path.exists(os.path.join(fd, t + ".tex")):
            lines.append(f"\\input{{figures/{t}.tex}}")
    with open(os.path.join(fd, "latex_includes.tex"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote figures/latex_includes.tex")


if __name__ == "__main__":
    main()
